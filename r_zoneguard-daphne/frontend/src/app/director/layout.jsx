const sidebarItems = [
  { label: 'Dashboard', href: '/director/dashboard', icon: Icons.dashboard },
  { label: 'Escalated Complaints', href: '/director/escalated_complaints', icon: Icons.complaints },
  { label: 'Executive Reports', href: '/director/executive_reports', icon: Icons.reports },
];

export default function DirectorLayout({ children }) {
  const pathname = usePathname();
  const router = useRouter();

  if (pathname.startsWith('/director/login')) {
    return <>{children}</>;
  }

  const handleLogout = (e) => {
    e.preventDefault();
    const confirmed = window.confirm('Are you sure you want to log out?');
    if (confirmed) {
      router.push('/director/login');
    }
  };

  return (
    <div className="director-layout-wrapper">
      <aside className="zg-sidebar">
        <div className="brand">
          <div className="brand-badge">ZG</div>
          <div>
            <div className="brand-title">ZoneGuard</div>
            <div className="brand-sub">NIA VILLAGE SUBD.</div>
          </div>
        </div>

        <nav className="nav-group">
          {sidebarItems.map((item) => {
            const isActive = pathname === item.href;
            return (
              <Link
                key={item.label}
                href={item.href}
                className={`nav-item ${isActive ? 'active' : ''}`}
              >
                <span className="nav-icon">{item.icon}</span>
                {item.label}
              </Link>
            );
          })}
        </nav>

        <div className="nav-footer">
          <Link href="/director/settings" className="nav-item">
            <span className="nav-icon">{Icons.settings}</span>
            Account Settings
          </Link>
          <button onClick={handleLogout} className="nav-item logout-btn" style={{ background: 'none', border: 'none', width: '100%', textAlign: 'left', cursor: 'pointer', font: 'inherit' }}>
            <span className="nav-icon">{Icons.logout}</span>
            Logout
          </button>
        </div>
      </aside>

      <div className="director-main-viewport">{children}</div>
    </div>
  );
}